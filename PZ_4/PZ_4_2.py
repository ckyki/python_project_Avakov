# Вариант 1
# Даны положительные числа А, B, C. на прямоугольнике размера A x B размещено
# максимально возможное количество квадратов со стороной С (без наложений).
# Найти количество квадратов, размещённый на прямоугольнике. Операции умножения и деления не использовать.

# Безопасный ввод a , b и c

while True:
    try:
        a = int(input("Введите положительное, целое число А: "))
        b = int(input("Введите положительное, целое число B: "))
        c = int(input("Введите положительное, целое число C: "))
        if a > 0 and b > 0 and c > 0:
            break
        print("Введённые числа должны быть ПОЛОЖИТЕЛЬНЫМИ")
    except ValueError:
        print("Введите ЦЕЛОЕ ЧИСЛО")

# Подсчёт кол-ва квадратов по стороне "а" (без деления)

count_a = 0
temp_a = a
while temp_a >= c:
    temp_a -= c
    count_a += 1

# Подсчёт кол-ва квадратов по стороне "B" (без деленя)

count_b = 0
temp_b = b
while temp_b >= c:
    temp_b -= c
    count_b += 1

# Подсчёт общего количества квадратов (замена умножения сложением)
total_squares = 0
i = 0
while i < count_a:
    total_squares += count_b
    i += 1

# Вывод результата
print("Количество квадратов на прямоугльнике:" , total_squares)